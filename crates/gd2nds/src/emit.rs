//! Writes the BlocksDS build directory for a project.
//!
//! The ROM template and the runtime sources are embedded in the gd2nds binary,
//! so a single executable is all a user needs besides BlocksDS.

use std::io;
use std::path::{Path, PathBuf};

use crate::project::ProjectConfig;

struct EmbeddedFile {
    path: &'static str,
    contents: &'static str,
}

macro_rules! embed {
    ($out:literal, $src:literal) => {
        EmbeddedFile {
            path: $out,
            contents: include_str!(concat!(env!("CARGO_MANIFEST_DIR"), "/../../", $src)),
        }
    };
}

const TEMPLATE_FILES: &[EmbeddedFile] = &[
    embed!("source/main.c", "templates/rom/source/main.c"),
    embed!("runtime/include/gdds/gdds.h", "runtime/include/gdds/gdds.h"),
    embed!("runtime/src/gdds.c", "runtime/src/gdds.c"),
];

const MAKEFILE_TEMPLATE: &str = include_str!(concat!(
    env!("CARGO_MANIFEST_DIR"),
    "/../../templates/rom/Makefile"
));

/// What `emit` produced.
#[derive(Debug)]
pub struct EmitOutput {
    pub build_dir: PathBuf,
    /// File name of the ROM `make` will produce, relative to `build_dir`.
    pub rom_name: String,
}

pub fn emit(config: &ProjectConfig, build_dir: &Path) -> io::Result<EmitOutput> {
    let title = config.name();
    let rom_stem = rom_stem(&title);

    for file in TEMPLATE_FILES {
        write_file(&build_dir.join(file.path), file.contents)?;
    }

    let makefile = MAKEFILE_TEMPLATE
        .replace("@NAME@", &rom_stem)
        .replace("@GAME_TITLE@", &makefile_safe(&title));
    write_file(&build_dir.join("Makefile"), &makefile)?;

    let header = format!(
        "/* Generated by gd2nds. Do not edit. */\n\
         #ifndef GD2NDS_PROJECT_H\n\
         #define GD2NDS_PROJECT_H\n\n\
         #define GD2NDS_PROJECT_NAME \"{}\"\n\
         #define GD2NDS_VERSION \"{}\"\n\n\
         #endif\n",
        c_string_escape(&title),
        env!("CARGO_PKG_VERSION"),
    );
    write_file(&build_dir.join("source/gd2nds_project.h"), &header)?;

    Ok(EmitOutput {
        build_dir: build_dir.to_path_buf(),
        rom_name: format!("{rom_stem}.nds"),
    })
}

fn write_file(path: &Path, contents: &str) -> io::Result<()> {
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent)?;
    }
    std::fs::write(path, contents)
}

/// A file-name-safe stem for the ROM, such as `hello_ds` for "Hello DS".
pub fn rom_stem(title: &str) -> String {
    let mut stem = String::new();
    for c in title.chars() {
        if c.is_ascii_alphanumeric() {
            stem.push(c.to_ascii_lowercase());
        } else if !stem.ends_with('_') && !stem.is_empty() {
            stem.push('_');
        }
    }
    let stem = stem.trim_end_matches('_');
    if stem.is_empty() {
        "game".to_string()
    } else {
        stem.to_string()
    }
}

/// The DS banner only shows ASCII well, and `#`/`$` mean something to make.
fn makefile_safe(text: &str) -> String {
    let cleaned: String = text
        .chars()
        .map(|c| match c {
            ' '..='~' if c != '#' && c != '$' && c != '\\' => c,
            _ => ' ',
        })
        .collect();
    let trimmed = cleaned.trim();
    if trimmed.is_empty() {
        "Untitled".to_string()
    } else {
        trimmed.to_string()
    }
}

/// Escape text for a C string literal, keeping only printable ASCII.
pub fn c_string_escape(text: &str) -> String {
    let mut out = String::new();
    for c in text.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            ' '..='~' => out.push(c),
            _ => out.push('?'),
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn rom_stem_is_file_safe() {
        assert_eq!(rom_stem("Hello DS"), "hello_ds");
        assert_eq!(rom_stem("  My -- Game!  "), "my_game");
        assert_eq!(rom_stem("ゲーム"), "game");
    }

    #[test]
    fn c_strings_are_escaped() {
        assert_eq!(c_string_escape(r#"a "b" \ é"#), r#"a \"b\" \\ ?"#);
    }

    #[test]
    fn makefile_title_drops_special_characters() {
        assert_eq!(makefile_safe("Cash $ Game #1"), "Cash   Game  1");
    }
}
